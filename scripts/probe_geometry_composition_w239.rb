  def clean_process(record)
    record.reject { |key, _| %w[stdout stderr path].include?(key) }
  end

  def successful?(record)
    record.fetch('classification') == 'process_success' && record.fetch('exitstatus') == 0 &&
      !record.fetch('signaled') && !record.fetch('timed_out') && !record.fetch('spawn_error')
  end

  def expected_refusal?(record, diagnostic, pattern)
    record.fetch('classification') == 'process_nonzero_or_signaled_exit' &&
      record.fetch('exitstatus') && record.fetch('exitstatus').positive? &&
      !record.fetch('signaled') && !record.fetch('timed_out') && !record.fetch('spawn_error') &&
      diagnostic.match?(pattern)
  end

  def varuint(value)
    require_true(value.is_a?(Integer) && value >= 0 && value <= 18_446_744_073_709_551_615,
      "invalid independent VarUInt literal: #{value.inspect}")
    bytes = []
    while value >= 0x80
      bytes << ((value & 0x7f) | 0x80)
      value >>= 7
    end
    (bytes << value).pack('C*').b
  end

  def rb_string(value)
    bytes = value.encode(Encoding::UTF_8).b
    varuint(bytes.bytesize) + bytes
  end

  def string_body(value)
    rb_string(value)
  end

  def u64(value)
    require_true(value.is_a?(Integer) && value >= 0 && value <= 18_446_744_073_709_551_615,
      "invalid independent UInt64 key: #{value.inspect}")
    [value].pack('Q<').b
  end

  def array_body(values)
    varuint(values.length) + values.map { |value| yield(value) }.join.b
  end

  def point_body(bits)
    require_true(bits.is_a?(Array) && bits.length == 2, 'Point fixture must have exactly two literal lanes')
    bits.map do |hex|
      require_true(/\A[0-9a-f]{16}\z/.match?(hex), "invalid Point lane literal #{hex.inspect}")
      [hex].pack('H*').b
    end.join.b
  end

  def geometry_body(value)
    return "\xff".b if value.nil?

    arm = value.fetch('arm')
    tag = GEO_TAGS.fetch(arm) { fail!("unlisted Geometry arm #{arm.inspect}") }
    item = value.fetch('value')
    case arm
    when 'Point'
      [tag].pack('C').b + point_body(item)
    when 'LineString', 'Ring', 'MultiPoint'
      [tag].pack('C').b + array_body(item) { |point| point_body(point) }
    when 'MultiLineString', 'Polygon'
      [tag].pack('C').b + array_body(item) do |line_or_ring|
        array_body(line_or_ring) { |point| point_body(point) }
      end
    when 'MultiPolygon'
      [tag].pack('C').b + array_body(item) do |polygon|
        array_body(polygon) do |ring|
          array_body(ring) { |point| point_body(point) }
        end
      end
    else
      fail!("unlisted Geometry body arm #{arm.inspect}")
    end
  end

  def value_body(profile, value)
    case profile.fetch('kind')
    when 'geometry'
      geometry_body(value)
    when 'array_geometry'
      array_body(value) { |geo_value| geometry_body(geo_value) }
    when 'tuple_string_geometry'
      string_body(value.fetch(0)) + geometry_body(value.fetch(1))
    when 'map_string_geometry'
      array_body(value) { |key, geo_value| string_body(key) + geometry_body(geo_value) }
    when 'nested_geometry_point'
      array_body(value) { |geo_value, point| geometry_body(geo_value) + point_body(point) }
    when 'nullable_tuple_geometry'
      value.nil? ? "\x01".b : "\x00".b + geometry_body(value.fetch(0))
    when 'variant_string_tuple_geometry'
      if value.nil?
        "\xff".b
      elsif value.fetch('arm') == 'String'
        "\x00".b + string_body(value.fetch('value'))
      elsif value.fetch('arm') == 'Tuple(geom Geometry)'
        "\x01".b + geometry_body(value.fetch('value'))
      else
        fail!("unlisted outer Variant arm #{value.fetch('arm').inspect}")
      end
    else
      fail!("unlisted profile value kind #{profile.fetch('kind').inspect}")
    end
  end

  def custom_descriptor(name)
    "\x2c".b + rb_string(name)
  end

  def type_descriptor(profile)
    case profile.fetch('id')
    when 'geometry'
      custom_descriptor('Geometry')
    when 'array_geometry'
      "\x1e".b + custom_descriptor('Geometry')
    when 'tuple_string_geometry'
      "\x20".b + varuint(2) + rb_string('label') + "\x15".b + rb_string('geom') + custom_descriptor('Geometry')
    when 'map_string_geometry'
      "\x27".b + "\x15".b + custom_descriptor('Geometry')
    when 'nested_geometry_point'
      "\x2f".b + varuint(2) + rb_string('geom') + custom_descriptor('Geometry') +
        rb_string('point') + custom_descriptor('Point')
    when 'nullable_tuple_geometry'
      "\x23".b + "\x20".b + varuint(1) + rb_string('geom') + custom_descriptor('Geometry')
    when 'variant_string_tuple_geometry'
      # Ordinary Variant children are ordered by full nominal name: String,
      # then Tuple(geom Geometry). This order is separate from Geometry's
      # hidden fixed local arm order.
      "\x2a".b + varuint(2) + "\x15".b + "\x20".b + varuint(1) +
        rb_string('geom') + custom_descriptor('Geometry')
    else
      fail!("unlisted W239 profile descriptor #{profile.fetch('id').inspect}")
    end
  end

  def expected_schema_header(profile)
    varuint(1) + rb_string('payload') + type_descriptor(profile)
  end

  def expected_rowbinary(profile)
    profile.fetch('values').map { |value| value_body(profile, value) }.join.b
  end

  def expected_insert_rows(profile)
    profile.fetch('keys').zip(profile.fetch('values')).map do |key, value|
      u64(key) + value_body(profile, value)
    end.join.b
  end

  def expected_rbnwt(profile)
    expected_schema_header(profile) + expected_rowbinary(profile)
  end

  class Probe
    include ProbeGeometryCompositionW239

    def initialize(options)
      @binary = R.validate_binary!(options.fetch(:clickhouse))
      @source_root = validate_source_root(options.fetch(:source_root))
      @output_root = R.validate_root(options.fetch(:output_root), OUTPUT_PREFIX, 'W239 stock output root')
      @store = File.join(@output_root, 'store')
      @records = []
      @profile_observations = []
      @refusal_observations = []
      @source_pin = nil
      @runtime_pin = nil
      @fatal = nil
      @recorder = nil
      @geometry_table_created = false
    end

    def run
      prepare_layout
      pin_source
      pin_runtime
      capture_profiles
      capture_refusals
      classification = final_classification
      write_matrix
      write_summary(classification)
      puts "W239 stock constructor/scalar profiles=#{@profile_observations.length}; evidence=#{@output_root}"
      classification == 'stock_geometry_composition_observed'
    rescue StandardError => error
      @fatal ||= "#{error.class}: #{error.message}"
      write_matrix rescue nil
      write_summary('stock_geometry_composition_probe_failed') rescue nil
      warn "W239 stock constructor/scalar probe failure; raw native status is preserved: #{@fatal}"
      false
    end

    private

    def validate_source_root(path)
      full = File.expand_path(path)
      require_true(File.directory?(full) && !File.symlink?(full) && File.realpath(full) == full,
        "pinned source checkout is absent, symlinked, or noncanonical: #{full}")
      require_true(full.start_with?(SOURCE_PREFIX) && File.basename(full) == 'clickhouse' &&
        File.dirname(File.dirname(full)) == File.realpath('/private/tmp'),
        'source checkout must be the pinned direct W238 /private/tmp checkout')
      full
    end

    def prepare_layout
      %w[invocations captures fixtures pins].each do |name|
        Dir.mkdir(File.join(@output_root, name), 0o700)
      end
      Dir.mkdir(@store, 0o700)
      @recorder = R::Recorder.new(@output_root, @binary)
    end

    def process(label, sql, input: nil, argv: nil)
      record = @recorder.run(label, @store, sql, input: input, argv: argv)
      @records << record
      record
    end

    def pin_source
      stdout, stderr, status = Open3.capture3('git', '-C', @source_root, 'rev-parse', 'HEAD')
      write_new(File.join(@output_root, 'pins', 'source-revision.stdout'), stdout.b)
      write_new(File.join(@output_root, 'pins', 'source-revision.stderr'), stderr.b)
      require_true(status.success? && stdout.strip == SOURCE_REVISION,
        "source revision differs from the separately pinned W239 source: #{stdout.inspect} #{stderr.inspect}")
      hashes = SOURCE_SHA256.map do |relative, expected|
        path = File.join(@source_root, relative)
        require_true(File.file?(path) && !File.symlink?(path), "source anchor is absent or symlinked: #{relative}")
        actual = Digest::SHA256.file(path).hexdigest
        { 'path' => relative, 'expected_sha256' => expected, 'actual_sha256' => actual,
          'matches' => actual == expected }
      end
      require_true(hashes.all? { |row| row.fetch('matches') }, 'a pinned W239 source anchor hash differs')
      @source_pin = {
        'checkout' => @source_root, 'revision' => SOURCE_REVISION,
        'runtime_built_from_this_source_not_asserted' => true,
        'source_scope' => 'separately fetched DataTypes/serialization source snapshot; not runtime provenance',
        'file_hashes' => hashes,
      }
      write_json(File.join(@output_root, 'pins', 'source-pin.json'), @source_pin)
    end

    def pin_runtime
      version = process('runtime-version-pin', 'SELECT version() FORMAT TSVRaw')
      require_true(successful?(version) && version.fetch('stdout').strip == R::VERSION,
        'native runtime differs from exact 26.10.1.1201 version pin')
      build = process('runtime-build-pin',
        "SELECT concat(name, '=', value) FROM system.build_options WHERE name='VERSION_GITHASH' FORMAT TSVRaw")
      require_true(successful?(build) && build.fetch('stdout').strip == "VERSION_GITHASH=#{R::BUILD_HASH}",
        'native runtime build hash differs from the exact W216 binary pin')
      @runtime_pin = {
        'version' => R::VERSION, 'build_hash' => R::BUILD_HASH,
        'sha256' => Digest::SHA256.file(@binary).hexdigest, 'binary' => @binary,
        'source_correlation' => 'not_asserted',
      }
      write_json(File.join(@output_root, 'pins', 'runtime-pin.json'), @runtime_pin)
    end

    def table(profile)
      "w239_stock_#{profile.fetch('id')}"
    end

    def capture_profiles
      PROFILES.each do |profile|
        row = {
          'id' => profile.fetch('id'), 'requested_type' => profile.fetch('declared_type'),
          'keys' => profile.fetch('keys'), 'row_count' => profile.fetch('values').length,
          'rowbinary_values_hex' => profile.fetch('values').map { |value| value_body(profile, value).unpack1('H*') },
          'descriptor_hex' => type_descriptor(profile).unpack1('H*'),
          'expected_rbnwt_hex' => expected_rbnwt(profile).unpack1('H*'),
        }
        begin
          capture_profile(profile, row)
        rescue StandardError => error
          row['classification'] = 'capture_or_oracle_error'
          row['error'] = "#{error.class}: #{error.message}"
        end
        @profile_observations << row
      end
    end

    def capture_profile(profile, row)
      id = profile.fetch('id')
      type = profile.fetch('declared_type')
      name = table(profile)
      input = expected_insert_rows(profile)
      expected_input_path = File.join(@output_root, 'fixtures', "#{id}.insert-rowbinary")
      expected_output_path = File.join(@output_root, 'fixtures', "#{id}.expected-rbnwt")
      write_new(expected_input_path, input)
      write_new(expected_output_path, expected_rbnwt(profile))
      row['independent_input_path'] = expected_input_path
      row['independent_expected_rbnwt_path'] = expected_output_path

      create_sql = [
        'SET flatten_nested=0',
        "CREATE TABLE default.#{name} (pk UInt64, payload #{type}) ENGINE=MergeTree ORDER BY pk SETTINGS #{STOCK_SETTINGS.join(', ')}",
        "INSERT INTO default.#{name} FORMAT RowBinary",
      ].join(";\n")
      create = process("create-insert-#{id}", create_sql, input: input)
      row['create_insert_process'] = clean_process(create)
      unless successful?(create)
        row['classification'] = 'candidate_constructor_or_scalar_input_failure'
        row['diagnostic'] = (create.fetch('stdout') + create.fetch('stderr')).force_encoding(Encoding::UTF_8).scrub
        return
      end
      @geometry_table_created = true if id == 'geometry'

      schema_sql = [
        'SET flatten_nested=0',
        "SELECT name, type FROM system.columns WHERE database='default' AND table='#{name}' ORDER BY position FORMAT TSVRaw",
      ].join(";\n")
      schema = process("schema-#{id}", schema_sql)
      row['schema_process'] = clean_process(schema)
      row['observed_schema_rows'] = schema.fetch('stdout').force_encoding(Encoding::UTF_8).scrub.lines.map(&:chomp) if successful?(schema)
      row['nominal_schema_matches'] = successful?(schema) &&
        row.fetch('observed_schema_rows') == ["pk\tUInt64", "payload\t#{type}"]

      part_sql = "SELECT name, toString(rows), toString(marks), part_type, path FROM system.parts " \
        "WHERE database='default' AND table='#{name}' AND active ORDER BY name FORMAT TSVRaw"
      part = process("stock-part-path-#{id}", part_sql)
      row['stock_part_process'] = clean_process(part)
      if successful?(part)
        part_rows = part.fetch('stdout').force_encoding(Encoding::UTF_8).scrub.lines.map(&:chomp)
        row['part_census_rows'] = part_rows
        if part_rows.length == 1
          fields = part_rows.first.split("\t", -1)
          if fields.length == 5
            row['part_census'] = {
              'name' => fields[0], 'rows' => fields[1].to_i, 'marks' => fields[2].to_i,
              'part_type' => fields[3], 'path' => fields[4],
            }
            path = File.expand_path(fields[4])
            if File.directory?(path) && !File.symlink?(path) && File.realpath(path) == path &&
                path.start_with?(File.realpath(@store) + File::SEPARATOR)
              row['stock_part_path'] = path
            end
          end
        end
      end

      rbnwt_sql = "SELECT payload FROM default.#{name} ORDER BY pk " \
        'SETTINGS output_format_binary_encode_types_in_binary_format=1, print_pretty_type_names=0, flatten_nested=0 ' \
        'FORMAT RowBinaryWithNamesAndTypes'
      binary = process("rowbinary-with-names-and-types-#{id}", rbnwt_sql)
      row['rbnwt_process'] = clean_process(binary)
      if successful?(binary)
        actual = binary.fetch('stdout').b
        capture_path = File.join(@output_root, 'captures', "#{id}.rowbinary-with-names-and-types")
        write_new(capture_path, actual)
        row['rbnwt'] = {
          'path' => capture_path, 'bytes' => actual.bytesize,
          'sha256' => Digest::SHA256.hexdigest(actual),
          'observed_hex' => actual.unpack1('H*'),
          'matches_independent_descriptor_and_values' => actual == expected_rbnwt(profile),
        }
      else
        row['rbnwt_diagnostic'] = (binary.fetch('stdout') + binary.fetch('stderr')).force_encoding(Encoding::UTF_8).scrub
      end
      row['classification'] = row.fetch('nominal_schema_matches', false) &&
        row.fetch('rbnwt', {}).fetch('matches_independent_descriptor_and_values', false) ?
        'constructor_and_scalar_observed' : 'constructor_or_scalar_divergence'
    end

    def capture_refusals
      REFUSALS.each do |item|
        table_name = "w239_refused_#{item.fetch('id')}"
        sql = "CREATE TABLE default.#{table_name} (payload #{item.fetch('type')}) ENGINE=Memory"
        record = process("constructor-refusal-#{item.fetch('id')}", sql)
        diagnostic = (record.fetch('stdout') + record.fetch('stderr')).force_encoding(Encoding::UTF_8).scrub
        expected = expected_refusal?(record, diagnostic, item.fetch('diagnostic'))
        @refusal_observations << {
          'id' => item.fetch('id'), 'requested_type' => item.fetch('type'),
          'classification' => expected ? 'expected_normal_constructor_refusal' : 'unexpected_constructor_outcome',
          'diagnostic' => diagnostic, 'process' => clean_process(record),
        }
      end
      capture_unknown_custom_descriptor
    end

    def capture_unknown_custom_descriptor
      unknown_name = 'CustomGeoW239Unknown'
      descriptor = custom_descriptor(unknown_name)
      input = varuint(1) + rb_string('payload') + descriptor
      input_path = File.join(@output_root, 'fixtures', 'unknown-custom-descriptor.rowbinary-with-names-and-types')
      write_new(input_path, input)
      if @geometry_table_created
        sql = 'INSERT INTO default.w239_stock_geometry (payload) FORMAT RowBinaryWithNamesAndTypes'
        argv = [@binary, 'local', '--path', @store, '--session_timezone=UTC', '--max_threads=1',
          '--max_insert_threads=1', '--max_execution_time=30', "--max_memory_usage=#{R::MEMORY_LIMIT_BYTES}",
          '--print_pretty_type_names=0', '--input_format_binary_decode_types_in_binary_format=1', '--query', sql]
        record = process('unknown-custom-descriptor-decode', sql, input: input, argv: argv)
        diagnostic = (record.fetch('stdout') + record.fetch('stderr')).force_encoding(Encoding::UTF_8).scrub
        expected = expected_refusal?(record, diagnostic, /Unknown data type family: CustomGeoW239Unknown/)
        @refusal_observations << {
          'id' => 'unknown_custom_descriptor', 'requested_type' => unknown_name,
          'descriptor_hex' => descriptor.unpack1('H*'), 'input_path' => input_path,
          'classification' => expected ? 'expected_normal_descriptor_refusal' : 'unexpected_descriptor_outcome',
          'diagnostic' => diagnostic, 'process' => clean_process(record),
        }
      else
        @refusal_observations << {
          'id' => 'unknown_custom_descriptor', 'requested_type' => unknown_name,
          'descriptor_hex' => descriptor.unpack1('H*'), 'input_path' => input_path,
          'classification' => 'not_run_geometry_control_unavailable',
        }
      end
    end

    def final_classification
      positives = @profile_observations.length == PROFILES.length &&
        @profile_observations.all? { |row| row.fetch('classification') == 'constructor_and_scalar_observed' }
      refusals = @refusal_observations.length == REFUSALS.length + 1 &&
        @refusal_observations.all? { |row| row.fetch('classification').start_with?('expected_normal_') }
      positives && refusals ? 'stock_geometry_composition_observed' : 'stock_geometry_composition_diverged_or_incomplete'
    end

    def coverage
      {
        'candidate_roster_method' => 'finite source-lawful representative declarations; no Cartesian expansion',
        'candidate_profile_count' => PROFILES.length,
        'candidate_profiles' => PROFILES.map { |profile| { 'id' => profile.fetch('id'), 'declared_type' => profile.fetch('declared_type') } },
        'fixed_geometry_arm_order' => GEO_TAGS,
        'outer_variant_order' => ['String', 'Tuple(geom Geometry)'],
        'refusal_count' => REFUSALS.length + 1,
        'refusal_types' => REFUSALS.map { |item| item.fetch('type') } + ['unknown Custom binary descriptor'],
        'physical_part_qualification' => false,
        'scope_limit' => 'constructor, nominal system.columns schema, and scalar RBNWT only; no part layout, CHECK, library writer, or recursive reader qualification',
      }
    end

    def write_matrix
      return unless @output_root && File.directory?(@output_root) && !File.exist?(File.join(@output_root, MATRIX_FILE))
      matrix = {
        'format' => MATRIX_FORMAT, 'coverage' => coverage,
        'profiles' => @profile_observations, 'refusal_observations' => @refusal_observations,
        'source_pin' => @source_pin, 'runtime_pin' => @runtime_pin,
        'rowbinary_output_settings' => [
          'output_format_binary_encode_types_in_binary_format=1', 'print_pretty_type_names=0', 'flatten_nested=0',
        ],
        'stock_merge_tree_settings' => STOCK_SETTINGS,
        'geometry_scalar_contract' => {
          'descriptor_hex' => custom_descriptor('Geometry').unpack1('H*'),
          'null_discriminator' => 255, 'arm_order' => GEO_TAGS,
          'geometry_descriptor_does_not_encode_hidden_fixed_arm_roster' => true,
        },
        'matrix_lineage' => 'Descriptors and RowBinary input/output fixtures are authored in this script before native execution; native source/runtime pins are recorded separately.',
      }
      write_json(File.join(@output_root, MATRIX_FILE), matrix)
    end

    def write_summary(classification)
      path = File.join(@output_root, 'summary.json')
      return unless @output_root && File.directory?(@output_root) && !File.exist?(path)
      process_rows = @records.map { |record| clean_process(record) }
      write_json(path, {
        'format' => SUMMARY_FORMAT, 'classification' => classification,
        'success' => classification == 'stock_geometry_composition_observed', 'error' => @fatal,
        'output_root' => @output_root, 'matrix_path' => File.join(@output_root, MATRIX_FILE),
        'coverage' => coverage, 'source_pin' => @source_pin, 'runtime_pin' => @runtime_pin,
        'profile_observations' => @profile_observations, 'refusal_observations' => @refusal_observations,
        'processes' => process_rows,
        'process_status_counts' => {
          'success_exit0' => process_rows.count { |row| row.fetch('classification') == 'process_success' },
          'normal_nonzero_or_signaled' => process_rows.count { |row| row.fetch('classification') == 'process_nonzero_or_signaled_exit' },
          'timeout' => process_rows.count { |row| row.fetch('classification') == 'process_timeout' },
          'spawn_failure' => process_rows.count { |row| row.fetch('classification') == 'spawn_failure' },
        },
      })
    end
  end

  def main(argv)
    options = {}
    parser = OptionParser.new do |opts|
      opts.banner = 'Usage: ruby scripts/probe_geometry_composition_w239.rb --clickhouse /private/tmp/crystal-click-w216-runtime-recovery.DmL9Kw/clickhouse-stripped --source-root /private/tmp/crystal-click-w238.4nQqSo/clickhouse --output-root /private/tmp/crystal-click-w239-stock.FRESH'
      opts.on('--clickhouse PATH', 'Pinned ClickHouse runtime binary') { |value| options[:clickhouse] = value }
      opts.on('--source-root PATH', 'Separately pinned W239 source checkout') { |value| options[:source_root] = value }
      opts.on('--output-root EMPTY_DIR', 'Fresh canonical direct /private/tmp output directory') { |value| options[:output_root] = value }
    end
    parser.parse!(argv)
    require_true(argv.empty? && %i[clickhouse source_root output_root].all? { |key| options.key?(key) }, parser.to_s)
    Probe.new(options).run
  rescue StandardError => error
    warn "W239 stock probe setup failure: #{error.class}: #{error.message}"
    false
  end
end

